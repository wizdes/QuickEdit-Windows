//! Where a character move may stop.
//!
//! This is a table-based copy of Unicode's grapheme rules (UAX 29). It exists because
//! `qe-a11y` cannot depend on `unicode-segmentation` under `cargo --locked`, and the
//! editor keeps its own stops private. It reads only the text around a position, and it
//! never answers inside a surrogate pair. The known gaps are in the README. When root
//! adds the editor hook named there, the callers in `text.rs` should use that instead.

fn in_table(table: &[(u32, u32)], c: char) -> bool {
    let c = c as u32;
    table
        .binary_search_by(|&(low, high)| {
            if c < low {
                std::cmp::Ordering::Greater
            } else if c > high {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

