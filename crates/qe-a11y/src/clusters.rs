fn is_joining(c: char) -> bool {
    in_table(JOINING, c)
}
fn is_pictographic(c: char) -> bool {
    in_table(PICTOGRAPHIC, c)
}
pub(crate) fn is_regional(c: char) -> bool {
    ('\u{1F1E6}'..='\u{1F1FF}').contains(&c)
}
fn is_prepend(c: char) -> bool {
    matches!(c as u32,
        0x600..=0x605 | 0x6DD | 0x70F | 0x890..=0x891 | 0x8E2 | 0x110BD | 0x110CD)
}
fn is_virama(c: char) -> bool {
    matches!(c as u32, 0x94D | 0x9CD | 0xACD | 0xB4D | 0xC4D | 0xD4D)
}
fn is_conjunct_consonant(c: char) -> bool {
    matches!(c as u32,
        0x915..=0x939 | 0x958..=0x95F | 0x995..=0x9B9 | 0xA95..=0xAB9 | 0xB15..=0xB39
        | 0xC15..=0xC39 | 0xD15..=0xD3A)
}
/// Control, line and paragraph separators, and format characters. Clusters end at these.
fn is_control(c: char) -> bool {
    c.is_control()
        || matches!(c as u32,
            0x200B | 0x200E | 0x200F | 0x2028..=0x202E | 0x2060..=0x206F | 0xFEFF | 0xFFF0..=0xFFFB
            | 0xE0000..=0xE001F | 0xE0080..=0xE00FF | 0xE01F0..=0xE0FFF)
}

#[derive(Clone, Copy, PartialEq)]
enum Hangul {
    Lead,
    Vowel,
    Trail,
    SyllableLv,
    SyllableLvt,
}
fn hangul(c: char) -> Option<Hangul> {
    Some(match c as u32 {
        0x1100..=0x115F | 0xA960..=0xA97C => Hangul::Lead,
        0x1160..=0x11A7 | 0xD7B0..=0xD7C6 => Hangul::Vowel,
        0x11A8..=0x11FF | 0xD7CB..=0xD7FB => Hangul::Trail,
        n @ 0xAC00..=0xD7A3 => {
            if (n - 0xAC00) % 28 == 0 {
                Hangul::SyllableLv
            } else {
                Hangul::SyllableLvt
            }
        }
        _ => return None,
    })
}

/// True when a caret may stop at byte `at` of `text`. `at` must be a character edge, or the
/// answer is true so that no caller reads inside a character. The ends of `text` count as
/// stops, so a caller passes enough text around `at`.
pub fn is_stop(text: &str, at: usize) -> bool {
    if at == 0 || at >= text.len() || !text.is_char_boundary(at) {
        return true;
    }
    let (Some(before), Some(after)) = (text.get(..at), text.get(at..)) else {
        return true;
    };
    let (Some(prev), Some(next)) = (before.chars().next_back(), after.chars().next()) else {
        return true;
    };
    if prev == '\r' && next == '\n' {
        return false;
    }
    if is_control(prev) || is_control(next) {
        return true;
    }
    if let (Some(a), Some(b)) = (hangul(prev), hangul(next)) {
        let joined = match a {
            Hangul::Lead => matches!(
                b,
                Hangul::Lead | Hangul::Vowel | Hangul::SyllableLv | Hangul::SyllableLvt
            ),
            Hangul::Vowel | Hangul::SyllableLv => matches!(b, Hangul::Vowel | Hangul::Trail),
            Hangul::Trail | Hangul::SyllableLvt => b == Hangul::Trail,
        };
        if joined {
            return false;
        }
    }
    // A character that attaches to the one after it, such as an Arabic number sign.
    if is_prepend(prev) {
        return false;
    }
    // An Indic consonant, a virama, and a consonant form one conjunct.
    if is_virama(prev) && is_conjunct_consonant(next) {
        let mut back = before.chars().rev().skip(1);
        if back.next().is_some_and(is_conjunct_consonant) {
            return false;
        }
    }
    if is_joining(next) {
        return false;
    }
    if prev == '\u{200D}' && is_pictographic(next) {
        for c in before.chars().rev().skip(1) {
            if is_pictographic(c) {
                return false;
            }
            if !is_joining(c) {
                break;
            }
        }
    }
    if is_regional(prev) && is_regional(next) {
        let run = before.chars().rev().take_while(|c| is_regional(*c)).count();
        return run % 2 == 0;
    }
    true
}
